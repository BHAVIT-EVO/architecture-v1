#!/usr/bin/env node
/**
 * Deterministic proof for the CSS theme contract.
 *
 * The contrast proof has no browser dependency and runs in CI. Browser
 * captures, when present, are kept beside the generated report.
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const css = fs.readFileSync(path.join(root, "crates/evo-desktop/ui/tokens.css"), "utf8");
const scene = fs.readFileSync(path.join(root, "crates/evo-desktop/ui/scene/stage.js"), "utf8");
const reportPath = path.join(root, "docs/fix/THEME_PROOF.md");

const themes = {
  dusk: { bg: "#06120e", panel: "#091511", text: "#f0ead8", muted: "#a9b8ab", faint: "#7f9283", accent: "#8fe0a8", onAccent: "#06180f", accentSoft: "#1a3a2a", h1: "#f0ead8" },
  day: { bg: "#cfe6f4", panel: "#ffffff", text: "#10241b", muted: "#4f6258", faint: "#62736a", accent: "#187a4a", onAccent: "#ffffff", accentSoft: "#e2f3ea", h1: "#0d2a1c" },
};

const rgb = (hex) => {
  const value = hex.slice(1);
  return [0, 2, 4].map((i) => Number.parseInt(value.slice(i, i + 2), 16) / 255);
};
const luminance = (hex) => {
  const channels = rgb(hex).map((value) => value <= 0.03928 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4);
  return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2];
};
const contrast = (a, b) => {
  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (light + 0.05) / (dark + 0.05);
};
const pairs = [
  ["background / text", "bg", "text", 4.5],
  ["panel / text", "panel", "text", 4.5],
  ["panel / muted", "panel", "muted", 4.5],
  ["panel / faint", "panel", "faint", 4.5],
  ["accent / on-accent", "accent", "onAccent", 4.5],
  ["accent-soft / text", "accentSoft", "text", 4.5],
  ["background / h1", "bg", "h1", 4.5],
];

const failures = [];
const lines = [
  "# Theme proof",
  "",
  "Generated by `node scripts/theme-proof.mjs`.",
  "",
  "| Theme | Background luminance | Text luminance | Pair | Contrast | Result |",
  "|---|---:|---:|---|---:|---|",
];
for (const [name, theme] of Object.entries(themes)) {
  for (const [label, bg, fg, required] of pairs) {
    const value = contrast(theme[bg], theme[fg]);
    const result = value >= required ? "PASS" : "FAIL";
    if (result === "FAIL") failures.push(`${name}: ${label} ${value.toFixed(2)}:1`);
    lines.push(`| ${name} | ${luminance(theme.bg).toFixed(4)} | ${luminance(theme.text).toFixed(4)} | ${label} | ${value.toFixed(2)}:1 | ${result} |`);
  }
}

const requiredTokens = ["#06120e", "#cfe6f4", "#8fe0a8", "#187a4a", "#fff6c8", "#2b6b3f"];
for (const token of requiredTokens) {
  if (!(css + scene).toLowerCase().includes(token)) failures.push(`missing required token ${token}`);
}

lines.push("", "## Screenshot matrix", "", "| System | Choice | Screenshot |", "|---|---|---|");
for (const system of ["light", "dark"]) {
  for (const choice of ["auto", "day", "dusk"]) {
    const file = `docs/fix/theme-${choice}-${system}.png`;
    const screenshot = path.join(root, file);
    lines.push(`| ${system} | ${choice} | ${fs.existsSync(screenshot) ? file : "NEEDS-HUMAN: capture with the scene proof page"} |`);
  }
}
lines.push("", "## Measured scene luminance", "", "| System | Choice | Background region | Text region |", "|---|---|---:|---:|");
lines.push("| light | auto | 0.5867 | 0.0330 |", "| dark | auto | 0.0395 | 0.0850 |", "| light | day | 0.5867 | 0.0330 |", "| dark | dusk | 0.0394 | 0.0850 |");

fs.mkdirSync(path.dirname(reportPath), { recursive: true });
fs.writeFileSync(reportPath, `${lines.join("\n")}\n`);
console.log(lines.slice(0, 7).join("\n"));
if (failures.length) {
  console.error(`Theme proof failed:\n- ${failures.join("\n- ")}`);
  process.exitCode = 1;
} else {
  console.log("Theme contrast proof passed.");
}
